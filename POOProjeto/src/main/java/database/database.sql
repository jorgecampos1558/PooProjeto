SELECT
j.nome,
j.time,
j.nacionalidade,
j.idade,
j.numero,
j.jogos,
a.gols,
a.assistencias,
a.xG
FROM jogadores j
JOIN atacante_stats a ON j.id = a.jogador_id
WHERE j.posicao = 'ST';

