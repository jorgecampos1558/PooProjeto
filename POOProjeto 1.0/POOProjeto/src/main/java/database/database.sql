-- ====================================================================
-- 1. CRIAÇÃO DAS TABELAS
-- ====================================================================

CREATE TABLE jogadores (
    id INT PRIMARY KEY AUTO_INCREMENT,
    nome VARCHAR(100),
    idade INT,
    posicao VARCHAR(10),
    numero INT,
    jogos INT,
    jogos_titular INT,
    minutos_jogados INT,
    time VARCHAR(50),
    nacionalidade VARCHAR(50),
    UNIQUE (nome, time, numero)
);

CREATE TABLE atacante_stats (
    id INT PRIMARY KEY AUTO_INCREMENT,
    jogador_id INT,
    gols INT,
    assistencias INT,
    finalizacoes INT,
    finalizacoes_no_gol INT,
    dribles_certos INT,
    perdas_de_posse INT,
    xG DOUBLE,
    grandes_chances_perdidas INT,
    FOREIGN KEY (jogador_id) REFERENCES jogadores(id) ON DELETE CASCADE
);

CREATE TABLE meio_stats (
    id INT PRIMARY KEY AUTO_INCREMENT,
    jogador_id INT,
    assistencias INT,
    passes_certos INT,
    passes_tentados INT,
    passes_decisivos INT,
    chances_criadas INT,
    desarmes INT,
    interceptacoes INT,
    bolas_recuperadas INT,
    perdas_de_posse INT,
    FOREIGN KEY (jogador_id) REFERENCES jogadores(id) ON DELETE CASCADE
);

CREATE TABLE defensor_stats (
    id INT PRIMARY KEY AUTO_INCREMENT,
    jogador_id INT,
    desarmes INT,
    interceptacoes INT,
    cortes INT,
    duelos_ganhos INT,
    duelos_tentados INT,
    faltas INT,
    duelosaereos_ganhos INT,
    duelosaereos_tentados INT,
    bolas_recuperadas INT,
    FOREIGN KEY (jogador_id) REFERENCES jogadores(id) ON DELETE CASCADE
);

CREATE TABLE goleiro_stats (
    id INT PRIMARY KEY AUTO_INCREMENT,
    jogador_id INT,
    defesas INT,
    defesas_dificeis INT,
    gols_sofridos INT,
    xg_contra DOUBLE,
    clean_sheets INT,
    penaltis_defendidos INT,
    FOREIGN KEY (jogador_id) REFERENCES jogadores(id) ON DELETE CASCADE
);

