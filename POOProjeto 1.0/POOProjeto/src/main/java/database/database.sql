SELECT
    j.nome,
    j.time,
    j.nacionalidade,
    j.idade,
    j.numero,
    m.assistencias,
    m.passes_certos,
    ROUND((m.passes_certos * 100.0) / m.passes_tentados, 1) AS precisao_passe
